"""
shared/schema.py
=================
공리원(전처리) · 주윤서(평가기) · 김기성(RL) 3인이 **공통으로 import**하는
단일 진실 공급원(Single Source of Truth).

왜 이 파일이 필요한가
----------------------
칼럼명을 각자 파일에 하드코딩하면, 오늘 회의에서 칼럼명이 바뀔 때마다
preprocessing/evaluator/rl_env 세 군데를 다 찾아다니며 고쳐야 하고,
그 과정에서 서로 다른 이름을 쓰게 되는 사고가 남.

그래서 "칼럼명이 무엇인가"라는 결정 하나만 이 파일에 모아두고,
나머지 세 사람의 코드는 전부 여기서 import해서 씀.
-> 오늘 칼럼명이 확정되면 이 파일 하나만 고치면 되고, 나머지 코드는
   한 줄도 안 고쳐도 그대로 동작해야 정상.

git 충돌 관련 참고
------------------
이 파일은 자주 바뀌지 않는 게 정상(오늘 한 번 확정하고 거의 고정).
수정 권한/타이밍은 팀이 합의해서 정하고(예: 공리원이 최종 반영),
merge 직전엔 항상 이 파일부터 pull 받고 시작할 것.
"""

